'use strict';
const fs = require('fs');
const os = require('os');
const path = require('path');
const store = require('./store');
const { report, fmtTok } = require('./report');
const { setup, off } = require('./setup');

const DAY = 86400000;
const HELP = `Usage: /warden <command>
  report [--session|--today|--week] [--md]   where your usage went (default: week)
  status                                      running subagents and budget used
  allow +50%                                  raise the last blocked agent's budget once
  setup | off                                 install or remove the status line wrapper
  on | pause                                  turn Warden on or off for all projects`;

function sessionFiles() {
  const dir = path.join(store.home(), 'sessions');
  try {
    return fs.readdirSync(dir).filter((f) => f.endsWith('.json'))
      .map((f) => ({ f, m: fs.statSync(path.join(dir, f)).mtimeMs })).sort((a, b) => b.m - a.m)
      .map(({ f }) => store.readJSON(`sessions/${f}`, null)).filter(Boolean);
  } catch { return []; }
}

function latestRateLimits() {
  const dir = path.join(store.home(), 'state');
  try {
    const f = fs.readdirSync(dir).filter((x) => x.endsWith('.json'))
      .sort((a, b) => fs.statSync(path.join(dir, b)).mtimeMs - fs.statSync(path.join(dir, a)).mtimeMs)[0];
    return f ? store.readJSON(`state/${f}`, {}).rate_limits : undefined;
  } catch { return undefined; }
}

// Restrict session totals to usage logged inside the window. Week % is scaled
// by the share of the agent's tokens that fall in the window.
function windowed(sessions, calls) {
  const byAgent = new Map();
  for (const c of calls) {
    const k = `${c.session}\0${c.id}`;
    const v = byAgent.get(k) || { tokens: 0, usd: 0, calls: 0 };
    v.tokens += c.tokens || 0; v.usd += c.usd || 0; v.calls += 1;
    byAgent.set(k, v);
  }
  return sessions.map((s) => {
    const agents = {};
    for (const [id, a] of Object.entries(s.agents || {})) {
      const w = byAgent.get(`${s.sid}\0${id}`);
      if (!w) continue;
      const sp = a.spent || {};
      const share = sp.tokens > 0 ? Math.min(1, w.tokens / sp.tokens) : 1;
      agents[id] = { ...a, spent: { weekPct: (sp.weekPct || 0) * share, tokens: w.tokens, usd: w.usd }, toolCalls: w.calls };
    }
    return { ...s, agents };
  }).filter((s) => Object.keys(s.agents).length);
}

function runReport(args, cwd = process.cwd()) {
  const all = sessionFiles();
  let sessions, since, label;
  if (args.includes('--session')) { sessions = all.slice(0, 1); since = sessions[0] ? sessions[0].startedAt : Date.now(); label = 'latest session'; }
  else if (args.includes('--today')) { since = Date.now() - DAY; label = 'last 24 hours'; }
  else { since = Date.now() - 7 * DAY; label = 'last 7 days'; }
  let calls;
  if (sessions) {
    const ids = new Set(sessions.map((s) => s.sid));
    calls = store.readLedger(since).filter((e) => e.type === 'call' && ids.has(e.session));
  } else {
    calls = store.readLedger(since).filter((e) => e.type === 'call');
    sessions = windowed(all.filter((s) => (s.updatedAt || s.startedAt || 0) >= since), calls);
  }
  const text = report({ sessions, calls, latest: latestRateLimits(), label });
  if (args.includes('--md')) {
    const file = path.join(cwd, `warden-report-${new Date().toISOString().slice(0, 10)}.md`);
    fs.writeFileSync(file, `# Warden report\n\n\`\`\`\n${text}\n\`\`\`\n\nGenerated by Warden. Figures are estimates from Claude Code's own usage numbers.\n`);
    return `${text}\n\nSaved ${file}`;
  }
  return text;
}

function status() {
  const s = sessionFiles()[0];
  if (!s) return 'No Warden data yet.';
  const live = Object.values(s.agents || {}).filter((a) => a.id !== 'main' && !a.ended);
  if (!live.length) return 'No subagents running in the latest session.';
  return live.map((a) => {
    const sp = a.spent || {};
    const mins = Math.round((Date.now() - (a.startedAt || Date.now())) / 60000);
    return `${a.agentType || 'subagent'} ${a.id}: ${sp.weekPct ? `${sp.weekPct.toFixed(2)}% week, ` : ''}${fmtTok(sp.tokens || 0)} tokens, ${a.toolCalls || 0} calls, ${mins} min${a.stoppedByWarden ? ' — stopped by Warden' : ''}`;
  }).join('\n');
}

function allow(spec) {
  const m = /^\+(\d+(?:\.\d+)?)%$/.exec(String(spec || '').trim());
  if (!m) return 'Usage: /warden allow +50%';
  const pct = Number(m[1]) / 100;
  for (const s of sessionFiles()) {
    const target = Object.values(s.agents || {}).filter((a) => a.lastDeniedAt).sort((a, b) => b.lastDeniedAt - a.lastDeniedAt)[0];
    if (!target) continue;
    store.update(`sessions/${s.sid}.json`, s, (cur) => {
      const a = cur.agents[target.id];
      a.allowance = (a.allowance || 0) + pct; a.denials = 0; a.lastDeniedAt = null;
      return cur;
    });
    store.appendLedger({ type: 'allow', session: s.sid, id: target.id, pct });
    return `Raised ${target.agentType || target.id}'s budget by ${m[1]}% for this run.`;
  }
  return 'Nothing is blocked right now.';
}

function setEnabled(on) {
  store.update('config.json', {}, (c) => ({ ...c, enabled: on }));
  return on ? 'Warden is on.' : 'Warden is paused. Run /warden on to resume.';
}

function main(argv, root, settingsFile = path.join(os.homedir(), '.claude', 'settings.json')) {
  const [cmd, ...rest] = argv;
  switch (cmd) {
    case 'report': return runReport(rest);
    case 'status': return status();
    case 'allow': return allow(rest[0]);
    case 'setup': return setup(settingsFile, root);
    case 'off': return off(settingsFile);
    case 'on': return setEnabled(true);
    case 'pause': return setEnabled(false);
    default: return HELP;
  }
}

module.exports = { main, allow, status, runReport, HELP };
